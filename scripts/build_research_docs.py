"""Regenerate the documentation that describes features, models and data schemas from the code itself.

    python scripts/build_research_docs.py

Writes features/feature_definitions.csv, docs/feature_engineering.md, models/model_registry.csv, models/README.md,
models/<algorithm>/{config.json, README.md, train.py, predict.py, evaluate.py}, data/schemas/*.csv and data/README.md.
Every number comes from quanara (feature catalogue, feature facts, saved model metadata, audit); nothing is typed in.
Needs the six competition files in data/raw/ and the saved models in artifacts/models/.
"""
from __future__ import annotations

import json
import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
warnings.filterwarnings("ignore")

import pandas as pd  # noqa: E402

from quanara import config, registry  # noqa: E402
from quanara import model_identity as MI  # noqa: E402
from quanara.data_loading import file_inventory, load_dataset  # noqa: E402
from quanara.dictionary import field_table  # noqa: E402
from quanara.feature_facts import (GROUP_LABEL, _FORMULA, _UNIT, assumptions, feature_rows, missing_reason, missing_treatment,  # noqa: E402
                                   scenario_sensitivity)
from quanara.features import CATALOG, MONOTONE_INCREASING, default_features  # noqa: E402
from quanara.integration import get_analytic  # noqa: E402
from quanara.leakage import timing_class  # noqa: E402
from quanara.models import ALGORITHM_INFO, HYPERPARAMS, MONOTONE_ALGORITHMS, default_params  # noqa: E402
from quanara.ui import features_page as FP  # noqa: E402  (pure helper functions; nothing is rendered)
from scripts.package_text import PREPROCESSING, RUN_COMMANDS  # noqa: E402

KNOWN = {"calendar": "known in advance (calendar)", "identifier": "known in advance (identifier)", "schedule": "scheduled capacity — known ahead from airline schedules",
         "history": "known 364+ days before the predicted date", "lagged_realised": "realised 7+ days before the predicted date",
         "realised": "realised on the day (set by the user in scenarios)", "retrospective": "observed only after the day (competition mode only)"}
FUNCTION = {"aviation": "quanara.features.aggregate_aviation → quanara.features.aviation_features",
            "derived": "quanara.features.aviation_features", "time": "quanara.features.time_features",
            "historical": "quanara.integration.history_frame", "market": "quanara.features.build_feature_frame (market key)",
            "competition": "quanara.integration.competition_extra"}
FOLDER = {"catboost": "catboost", "random_forest": "random_forest", "xgboost": "xgboost", "ridge": "ridge", "svr": "support_vector_regression",
          "seasonal_naive": "seasonal_naive", "extra_trees": "extra_trees"}


def write(rel: str, text: str) -> None:
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


def features_docs(a) -> None:
    moved = scenario_sensitivity(a)
    rows_by = {(sc, mo): {r.name: r for r in feature_rows(a, sc, mo, moved)} for sc in config.SCOPES for mo in config.MODES}
    recs, md = [], ["# Feature engineering", "",
                    "Generated by `scripts/build_research_docs.py` from the feature catalogue (`quanara/features.py`) and the feature facts "
                    "(`quanara/feature_facts.py`). Missing-value shares are measured on the training rows of each scope in What-if mode "
                    "(Competition mode for hotel-observation features).", "",
                    "## Raw inputs and engineered features", "",
                    "**Raw aviation variables** are columns of `flight_data.xlsx` at route-day grain: Total Seats, Total PAX, Total P2P, Total Transfer, "
                    "Total Transit, Average Weekly Frequency (decoded to flights), Load Factor, Departure Country/City, Airline Name and cabin-level counts. "
                    "Only the daily rows (from 2023-01-01) feed features; the 2022 monthly rows are never spread over days.", "",
                    "**Engineered features** are computed from those columns after summing route-day rows per day (or per day × departure country for "
                    "the market scope) on a complete calendar, where a day without a row counts as zero flights. Ratios are always recomputed from summed "
                    "numerators and denominators. Trailing windows include the current day: a 7-day window on day t covers t−6 … t.", "",
                    "| Group | Features |", "|---|---|"]
    for g in dict.fromkeys(f.group for f in CATALOG):
        md.append(f"| {GROUP_LABEL[g]} | {', '.join(f'`{f.name}`' for f in CATALOG if f.group == g)} |")
    md += ["", "## Feature by feature", ""]
    for fs in CATALOG:
        mo = "whatif" if "whatif" in fs.modes else "competition"
        r_tot, r_mkt = rows_by[("international_total", mo)].get(fs.name), rows_by[("international_market", mo)].get(fs.name)
        defaults = [sc for sc in config.SCOPES if fs.name in default_features(sc, mo)]
        rec = {"feature": fs.name, "label": fs.label, "group": GROUP_LABEL[fs.group], "kind": fs.kind, "source_columns": fs.source,
               "formula": _FORMULA.get(fs.name, ""), "unit": _UNIT.get(fs.name, FP._unit_of(fs.name)), "time_window": FP._time_window(fs.name),
               "aggregation_total_scopes": FP._aggregation(fs.name, "international_total"), "aggregation_market_scope": FP._aggregation(fs.name, "international_market"),
               "missing_handling": missing_treatment(fs.name), "missing_reason": missing_reason(fs.name, "international_total", mo),
               "missing_pct_total_scope": round(r_tot.missing_pct, 4) if r_tot and r_tot.missing_pct >= 0 else "",
               "missing_pct_market_scope": round(r_mkt.missing_pct, 4) if r_mkt and r_mkt.missing_pct >= 0 else "",
               "known_when": KNOWN[timing_class(fs.name)], "leakage_risk": r_tot.leakage if r_tot else "", "leakage_justification": r_tot.leakage_why if r_tot else "",
               "modes": " · ".join("What-if" if m == "whatif" else "Competition" for m in fs.modes), "moves_in_scenarios": r_tot.scenario if r_tot else "",
               "monotone_constraint": "non-decreasing (tree models)" if fs.name in MONOTONE_INCREASING else "none",
               "default_in_scopes": ", ".join(defaults) or "—", "interpretation": fs.definition, "implemented_in": FUNCTION[fs.group]}
        recs.append(rec)
        md += [f"### `{fs.name}` — {fs.label}", "", "| | |", "|---|---|"] + [f"| {k.replace('_', ' ').capitalize()} | {str(v).replace('|', '/')} |" for k, v in rec.items()
                                                                            if k not in ("feature", "label")]
        extra = assumptions(fs.name, "international_total")
        if extra:
            md += ["", "Assumptions and limitations:", ""] + [f"- {x}" for x in extra]
        md.append("")
    write("features/feature_definitions.csv", pd.DataFrame(recs).to_csv(index=False))
    write("docs/feature_engineering.md", "\n".join(md) + "\n")
    print(f"features: {len(recs)} definitions → features/feature_definitions.csv, docs/feature_engineering.md")


def model_docs() -> None:
    models = registry.list_models()
    labels = MI.labels(models)
    reg = []
    for m in models:
        h, cv = m["metrics_holdout"], m.get("metrics_cv_mean") or {}
        reg.append({"model_id": m["model_id"], "model": labels[m["model_id"]], "algorithm": MI.algorithm(m), "target": MI.target(m), "grain": MI.scope(m),
                    "mode": MI.mode(m), "n_features": len(m["features"]), "eval_fit_start": m["periods"]["eval_fit"][0], "eval_fit_end": m["periods"]["eval_fit"][1],
                    "holdout_start": m["periods"]["holdout"][0], "holdout_end": m["periods"]["holdout"][1], "deployment_fit_end": m["periods"]["deployment_fit"][1],
                    "holdout_rows": m["n_rows"]["holdout"], "MAE": h["MAE"], "RMSE": h["RMSE"], "R2": h["R2"], "WMAPE": h["WMAPE"], "cv_WMAPE": cv.get("WMAPE"),
                    "log_target": m.get("log_target"), "monotone": m.get("monotone"), "negative_policy": m.get("negative_policy", "none"),
                    "reference_model": bool(m.get("reference")), "simulator_ready": MI.scenario_ready(m), "trained_at": m["created_at"],
                    "folder": f"models/{FOLDER[m['algorithm']]}/"})
    rdf = pd.DataFrame(reg)
    write("models/model_registry.csv", rdf.to_csv(index=False, float_format="%.6g"))
    algos = list(dict.fromkeys(m["algorithm"] for m in models))
    for algo in algos:
        mine = [m for m in models if m["algorithm"] == algo]
        folder = FOLDER[algo]
        cfg = {"algorithm": algo, "name": MI.ALGORITHMS[algo], "description": ALGORITHM_INFO[algo][0], "preprocessing": PREPROCESSING[algo],
               "supports_monotone_constraint": algo in MONOTONE_ALGORITHMS, "default_hyperparameters": default_params(algo),
               "hyperparameter_space": {k: {"label": v[0], "type": v[1], "default": v[2], "range_or_choices": v[3] if v[1] == "choice" else [v[3], v[4]], "help": v[6]}
                                        for k, v in HYPERPARAMS[algo].items()},
               "models": []}
        for m in mine:
            cfg["models"].append({"model_id": m["model_id"], "label": labels[m["model_id"]], "reference_model": bool(m.get("reference")),
                                  "target_definition": f"{MI.target(m)} — {MI.unit(m)} ({m['scope_label']})", "scope": m["scope"], "grain": m["grain"],
                                  "mode": m["mode"], "mode_definition": config.MODES[m["mode"]], "features": m["features"],
                                  "hyperparameters": m["params"] or default_params(algo), "log_target": m.get("log_target"), "monotone": m.get("monotone"),
                                  "monotone_features": [f for f in m["features"] if f in MONOTONE_INCREASING] if (m.get("monotone") and algo in MONOTONE_ALGORITHMS) else [],
                                  "negative_policy": m.get("negative_policy", "none"), "seed": m["config"].get("seed"),
                                  "periods": m["periods"], "rows": m["n_rows"], "cross_validation": {"folds": m["config"].get("cv_folds"), "horizon_days": m["config"].get("cv_horizon_days")},
                                  "training_dataset": f"quanara.integration.model_frame(scope='{m['scope']}', mode='{m['mode']}') → training_rows, {m['periods']['eval_fit'][0]} → {m['periods']['eval_fit'][1]} for evaluation, refit on {m['periods']['deployment_fit'][0]} → {m['periods']['deployment_fit'][1]}",
                                  "artifacts": {"deployment_pipeline": f"artifacts/models/{m['model_id']}/model_final.joblib",
                                                "evaluation_pipeline": f"artifacts/models/{m['model_id']}/model_eval.joblib",
                                                "holdout_predictions": f"artifacts/models/{m['model_id']}/predictions_holdout.csv"},
                                  "holdout_metrics": m["metrics_holdout"], "cv_mean_metrics": m.get("metrics_cv_mean"), "software": m.get("versions"),
                                  "trained_at": m["created_at"], "simulator_ready": MI.scenario_ready(m), "not_ready_reason": MI.not_ready_reason(m),
                                  "training_config": m["config"]})
        write(f"models/{folder}/config.json", json.dumps(cfg, indent=2, default=str) + "\n")
        for action in ("train", "predict", "evaluate"):
            write(f"models/{folder}/{action}.py",
                  f'"""{MI.ALGORITHMS[algo]} — {action}. Run with --help for options; see README.md in this folder."""\n'
                  "import sys\nfrom pathlib import Path\n\nsys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))\n"
                  "from models.workflow import main  # noqa: E402\n\n"
                  f'if __name__ == "__main__":\n    sys.exit(main("{algo}", "{action}"))\n')
        tbl = ["| Model ID | Target | Mode | Features | Holdout | MAE | RMSE | R² | WMAPE | Simulator |", "|---|---|---|---|---|---|---|---|---|---|"]
        for m in mine:
            h = m["metrics_holdout"]
            tbl.append(f"| `{m['model_id']}`{' (reference)' if m.get('reference') else ''} | {MI.target(m, short=True)} | {MI.mode(m)} | {len(m['features'])} | "
                       f"{m['periods']['holdout'][0]} → {m['periods']['holdout'][1]} | {h['MAE']:,.1f} | {h['RMSE']:,.1f} | {h['R2']:.3f} | {h['WMAPE']:.1%} | "
                       f"{'ready' if MI.scenario_ready(m) else 'no'} |")
        first = mine[0]["model_id"]
        hp = "\n".join(f"| `{k}` | {v[0]} | {v[2]} | {v[3] if v[1] == 'choice' else f'{v[3]} – {v[4]}'} | {v[6]} |" for k, v in HYPERPARAMS[algo].items()) or "| — | No hyperparameters | | | |"
        write(f"models/{folder}/README.md", "\n".join([
            f"# {MI.ALGORITHMS[algo]}", "", ALGORITHM_INFO[algo][0], "",
            "## Pipeline", "", PREPROCESSING[algo], "",
            "Every saved artefact is the complete pipeline (preprocessing + estimator), so predicting needs only the feature columns listed in `config.json`.", "",
            "## Hyperparameters", "", "| Name | Meaning | Default | Range | Note |", "|---|---|---|---|---|", hp, "",
            f"## Saved models ({len(mine)})", "",
            "Metrics are on the chronological holdout recorded with each model and are recomputed from its saved predictions by `evaluate.py`. "
            "Compare only models with the same target and holdout (see `models/model_registry.csv`).", "", *tbl, "",
            "Training, validation and deployment dates, the full feature list, preprocessing options and software versions of each model are in `config.json`.", "",
            "## Run", "", "```bash", RUN_COMMANDS.format(folder=folder, first=first).strip(), "```", "",
            "## Reproducibility status", "",
            "The prediction side is verified: `tests/test_legacy_artifacts.py` reloads every saved pipeline and reproduces its saved holdout predictions. "
            "Re-fitting was **not** re-run when this package was assembled (no model was retrained). `train.py --from <model_id> --no-save` refits the "
            "recorded configuration in memory and prints the recorded and new metrics side by side, so the training side can be checked on your machine. "
            "Tree ensembles are seeded (seed 42); small differences can still arise from library versions or thread scheduling.", ""]) + "\n")
    lines = ["# Models", "", "Every algorithm that has at least one saved model has its own folder with `train.py`, `predict.py`, `evaluate.py`, "
             "`config.json` (features, hyperparameters, dates, target, preprocessing, artefact paths, verified metrics) and a README.", "",
             "| Algorithm | Folder | Saved models | Reference models |", "|---|---|---|---|"]
    for algo in algos:
        mine = [m for m in models if m["algorithm"] == algo]
        lines.append(f"| {MI.ALGORITHMS[algo]} | `models/{FOLDER[algo]}/` | {len(mine)} | {sum(bool(m.get('reference')) for m in mine)} |")
    lines += ["", "Extra Trees is implemented in `quanara/models.py` and offered in the ML Training Studio, but no Extra Trees model has been saved, so it has no folder.", "",
              "## Prediction scopes", "", "| Scope | Target | Grain |", "|---|---|---|"]
    lines += [f"| `{sc}` | {MI.TARGETS[sc]} | {MI.SCOPES[sc]} |" for sc in config.SCOPES]
    lines += ["", "Modes: **What-if** models use aviation, calendar and last-year guests and can drive the simulator. **Competition** models may also use same-day hotel "
              "arrivals (New Arrivals, Same-Day Guests) present in the official test files; they score the test period but cannot run scenarios.", "",
              "## Artefacts", "", "The trained pipelines (`artifacts/models/<model_id>/model_final.joblib`, `model_eval.joblib`) and their prediction files are not part of "
              "this package: they are derived from the restricted competition data. `models/model_registry.csv` and each `config.json` keep every configuration and "
              "verified metric. Rebuild the reference models with `python scripts/train_reference_models.py` after placing the data (see `data/README.md`).", ""]
    write("models/README.md", "\n".join(lines) + "\n")
    print(f"models: {len(models)} saved models, {len(algos)} algorithm folders → models/")


def data_docs() -> None:
    ft = field_table()
    labels = {"intl_train": "International hotel guests — train", "intl_test": "International hotel guests — test",
              "dom_train": "Domestic hotel guests — train", "dom_test": "Domestic hotel guests — test", "flight": "Flight operations"}
    inv = {r["dataset"]: r for r in file_inventory()} if isinstance(file_inventory(), list) else {r["dataset"]: r for r in file_inventory().to_dict("records")}
    rows_md = []
    for k, lab in labels.items():
        df = load_dataset(k)
        cols = [c for c in df.columns if c not in ("same_day_suppressed", "grain", "flights", "flights_decode_error", "market_key")]
        sch = []
        for c in cols:
            f = ft[(ft["column"] == c)]
            sch.append({"column": c, "dtype_after_cleaning": str(df[c].dtype), "role": f["role"].iloc[0] if len(f) else "",
                        "description": f["definition"].iloc[0] if len(f) else "", "empty_cells_pct": round(float(df[c].isna().mean() * 100), 3)})
        write(f"data/schemas/{k}.csv", pd.DataFrame(sch).to_csv(index=False))
        i = inv.get(k, {})
        rows_md.append(f"| {lab} | `{i.get('file', '')}` | {len(df):,} | {df['Date'].min():%Y-%m-%d} → {df['Date'].max():%Y-%m-%d} | `schemas/{k}.csv` |")
    d = inv.get("dictionary", {})
    write("data/README.md", "\n".join([
        "# Data", "", "QuanAra uses only the six files supplied for the DCT Abu Dhabi ChallengeON 2026. **They are not included in this package.** "
        "Place your authorised copies in `data/raw/` with their original names (or set `QUANARA_DATA_DIR` to the folder that holds them). "
        "The application reads them read-only and never modifies them.", "",
        "| Dataset | File | Rows | Dates | Schema |", "|---|---|---|---|---|", *rows_md,
        f"| Data dictionary | `{d.get('file', 'Data_Dictionary.pdf')}` | — | — | quoted in the Data Intelligence page |", "",
        "## Check your copies", "", "`SHA256SUMS.txt` lists the checksums of the files this project was built and verified with:", "",
        "```bash", "cp data/SHA256SUMS.txt data/raw/ && cd data/raw && shasum -a 256 -c SHA256SUMS.txt", "```", "",
        "## Derived folders (created at run time, git-ignored)", "",
        "- `data/processed/` — model matrices written by `features/build_features.py` and `scripts/build_dataset.py`",
        "- `data/cache/` — cached analytical dataset", "- `artifacts/` — trained pipelines, predictions and saved scenarios", ""]) + "\n")
    print(f"data: {len(labels)} schemas → data/schemas/, data/README.md")


if __name__ == "__main__":
    a = get_analytic()
    features_docs(a)
    model_docs()
    data_docs()
